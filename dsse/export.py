def _blob(a) -> dict:
    a = np.ascontiguousarray(np.asarray(a, dtype="<f4"))
    return {"shape": list(a.shape), "data": base64.b64encode(a.tobytes()).decode("ascii")}


def unblob(b: dict) -> np.ndarray:
    return np.frombuffer(base64.b64decode(b["data"]), dtype="<f4").reshape(b["shape"])


def gnn_json(model, norm: train.Normalizer, fd: G.Feeder, about: dict) -> dict:
    """The model's weights, with each NNConv's edge network already applied: the browser gets one
    [in, out] matrix per line and layer instead of the network that makes them."""
    model.eval()
    ea = torch.tensor(np.stack([fd.r, fd.x], 1), dtype=torch.float32)  # one row per line
    ea = (ea - norm.e_mean) / norm.e_std
    layers = []
    with torch.no_grad():
        for conv, ln in ((model.conv1, model.norm1), (model.conv2, model.norm2)):
            theta = conv.nn(ea).reshape(len(fd.t), conv.in_channels_l, conv.out_channels)
            layers.append({
                "in": conv.in_channels_l, "out": conv.out_channels,
                "theta": _blob(theta), "root": _blob(conv.lin.weight.T), "bias": _blob(conv.bias),
                "norm_weight": _blob(ln.weight), "norm_bias": _blob(ln.bias), "norm_eps": ln.eps,
            })
        out = {"weight": _blob(model.lin.weight.T), "bias": _blob(model.lin.bias)}
    lines = np.arange(len(fd.t))
    return {
        "source": SOURCE,
        "model": "gnn-anymeter",
        **about,
        "format": "Each tensor is base64 of little-endian float32, row-major, with its shape.",
        "forward": [
            "x = (features - x_mean) / x_std, per bus (17 features, feeder.json gnn_features; x_std is 1 where the "
            "feature never varied in training).",
            "Layer (twice): out_i = mean over edges j->i of x_j . theta[line] + x_i . root + bias, where theta[line] "
            "is [in, out] and both directions of a line share it; then LayerNorm over the out features of each bus "
            "(mean, biased variance, eps), times norm_weight plus norm_bias; then ReLU.",
            "x1 = layer 1 (17->64), x2 = layer 2 (64->64) on x1; h = x1 + x2; z = h . out.weight + out.bias ([64, 2]).",
            "|V| = y_mean[0] + y_std[0] z[0], angle (rad) = y_mean[1] + y_std[1] z[1]. Dropout is off at inference.",
        ],
        "edges": {
            "note": "PyG's order: the 32 lines from -> to, then the same 32 to -> from.",
            "from": np.concatenate([fd.f, fd.t]).tolist(), "to": np.concatenate([fd.t, fd.f]).tolist(),
            "line": np.concatenate([lines, lines]).tolist(),
        },
        "layers": layers,
        "out": out,
        "normaliser": {
            "x_mean": norm.x_mean.tolist(), "x_std": norm.x_std.tolist(),
            "y_mean": norm.y_mean.tolist(), "y_std": norm.y_std.tolist(),
        },
    }


def forward_np(g: dict, features: np.ndarray):
    """The forward pass gnn.json describes, in float64 numpy: the browser's reference."""
    nm = g["normaliser"]
    x = (features - np.array(nm["x_mean"])) / np.array(nm["x_std"])
    src, dst, line = (np.array(g["edges"][k]) for k in ("from", "to", "line"))
    deg = np.bincount(dst, minlength=len(x)).astype(float)
    outs = []
    for L in g["layers"]:
        theta = unblob(L["theta"]).astype(float)
        msg = np.einsum("ei,eio->eo", x[src], theta[line])
        agg = np.zeros((len(x), L["out"]))
        np.add.at(agg, dst, msg)
        agg /= np.maximum(deg, 1)[:, None]
        h = agg + x @ unblob(L["root"]).astype(float) + unblob(L["bias"]).astype(float)
        mu, var = h.mean(1, keepdims=True), h.var(1, keepdims=True)
        h = (h - mu) / np.sqrt(var + L["norm_eps"]) * unblob(L["norm_weight"]) + unblob(L["norm_bias"])
        x = np.maximum(h, 0.0)
        outs.append(x)
    z = (outs[0] + outs[1]) @ unblob(g["out"]["weight"]).astype(float) + unblob(g["out"]["bias"]).astype(float)
    return nm["y_mean"][0] + nm["y_std"][0] * z[:, 0], nm["y_mean"][1] + nm["y_std"][1] * z[:, 1]


