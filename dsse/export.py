def _write(path: Path, obj, compact: bool = False) -> int:
    path.parent.mkdir(parents=True, exist_ok=True)
    text = json.dumps(obj, separators=(",", ":")) if compact else json.dumps(obj, indent=1, ensure_ascii=False)
    path.write_text(text + "\n", encoding="utf-8", newline="\n")
    return path.stat().st_size


def main():
    grid = G.load_gridcal()
    fd = G.feeder(grid)
    _, s_base = G.gridcal_power_flow(grid, fd.p_load, fd.q_load)
    prior = scenarios.pseudo_prior(fd, s_base)

    seed = phase2.chosen_anymeter()
    run = json.loads((phase2.RUNS / f"gnn-anymeter_seed{seed}" / "result.json").read_text(encoding="utf-8"))
    _, _, model, norm = phase2.load_model(phase2.RUNS / f"gnn-anymeter_seed{seed}")
    gnn = gnn_json(model, norm, fd, {
        "seed": seed, "trained_on": "0 to 33 meters, 0 to 2 PMUs",
        "validation_vm_mae_pu": run["validation"]["vm_mae"], "test_vm_mae_pu_10_meters": run["per_sample"]["vm_mae"],
    })
    gnn = json.loads(json.dumps(gnn))  # exactly what the browser will read
    _, _, _, _, te_s = phase2.split()
    gap = max(np.abs(np.stack(gnn_predict(model, norm, fd, s)) - np.stack(forward_np(gnn, features(fd, s)))).max()
              for s in te_s[:100])
    if gap > 1e-5:
        raise RuntimeError(f"gnn.json's forward pass is {gap:.1e} from the model's")

    report = json.loads((paths.REPORTS / "results.json").read_text(encoding="utf-8"))
    sizes = {
        "feeder.json": _write(CONTENT / "feeder.json", feeder_json(fd, s_base)),
        "gnn.json": _write(CONTENT / "gnn.json", gnn, compact=True),
        "results.json": _write(CONTENT / "results.json", results_json(report, float(s_base[0].real))),
    }
    (CONTENT / "README.md").write_text(README, encoding="utf-8", newline="\n")
    sizes["README.md"] = (CONTENT / "README.md").stat().st_size
    sizes["fixtures.json (not shipped)"] = _write(FIXTURES, fixtures(fd, grid, prior, gnn, model, norm), compact=True)
    print(f"gnn-anymeter seed {seed}; gnn.json's forward pass within {gap:.1e} of torch's on 100 test samples")
    for name, size in sizes.items():
        print(f"{name}: {size / 1024:.0f} KB")


if __name__ == "__main__":
    main()
