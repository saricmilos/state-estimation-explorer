    cases = []
    for name, k, n_pmu, factor, gross in CASES:
        f = 1.0 + scenarios.LOAD_SPREAD * rng.normal(size=fd.n) if factor is None else np.full(fd.n, factor)
        p_load, q_load = fd.p_load * f, fd.q_load * f
