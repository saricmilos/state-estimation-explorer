class RecordingRng:
    """A numpy Generator that writes down every draw scenarios.measure takes, in order, so the port can
    replay them and must arrive at the same readings. measure only calls random, normal and uniform."""

    def __init__(self, rng):
        self._rng = rng
        self.draws = []

    def random(self):
        v = float(self._rng.random())
        self.draws.append({"fn": "random", "value": v})
        return v

    def normal(self, loc, scale):
        v = float(self._rng.normal(loc, scale))
        self.draws.append({"fn": "normal", "loc": float(loc), "scale": float(scale), "value": v})
        return v

    def uniform(self, low, high):
        v = float(self._rng.uniform(low, high))
        self.draws.append({"fn": "uniform", "low": float(low), "high": float(high), "value": v})
        return v

    def __getattr__(self, name):
        raise AttributeError(f"measure() drew with {name}, which the fixtures don't record")


def _state(v, s=None):
    out = {"vm": _round(np.abs(v), 15), "va": _round(np.angle(v), 15)}
    if s is not None:
        out |= {"p_mw": _round(s.real, 15), "q_mvar": _round(s.imag, 15)}
    return out


def _wls(fd, smp, angles):
    e = wls_np.estimate(fd, smp, angles)
    out = {"observable": e.observable, "iterations": e.iterations, "readings": len(e.readings)}
    if e.observable:
        c = wls_np.chi_square(e)
        out |= {"converged": e.converged, **_state(e.v), "objective": _round(c["J"], 15), "dof": c["dof"],
                "chi2_limit": _round(c["limit"], 15)}
    return out


